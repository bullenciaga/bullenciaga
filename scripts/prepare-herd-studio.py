"""Build the public studio palette from a local copy of the original aligned PNGs."""
import json
import sys
from functools import lru_cache
from pathlib import Path

from PIL import Image

source = Path(sys.argv[1])
site = Path(__file__).resolve().parents[1] / "site"
art = site / "assets/herd-studio"
# Within each collection category these are the everyday editions.
options = {
    "fur": {"Black": "BULL/BLACK", "White": "BULL/WHITE", "Brown": "BULL/BROWN", "Grey": "BULL/GREY"},
    "horns": {"White": "HORNS/WHITE", "Black": "HORNS/BLACK"},
    "clothing": {
        "Grey turtleneck": "MIDWEAR/GREY-TURTLENECK", "Black turtleneck": "MIDWEAR/BLACK-TURTLENECK",
        "White tee": "INNERWEAR/WHITE-TSHIRT", "Black tee": "INNERWEAR/BLACK-TSHIRT",
        "Track jacket": "MIDWEAR/ZIPPED-UP-TRACKSUIT", "White tank": "INNERWEAR/WHITE-TANKTOP",
        "Black hoodie": "INNERWEAR/WHITE-TSHIRT|OUTERWEAR/BLACK-HOODIE",
        "Two-tone jacket": "INNERWEAR/WHITE-TSHIRT|OUTERWEAR/BLACK-GREY-JACKET",
    },
    "eyewear": {"Black glasses": "GLASSES AND HEADGEAR/BLACK-BASIC-GLASSES"},
    "headwear": {"Black cap": "HATS/BLACK-CAP", "Black beanie": "HATS/BLACK-BEANIE", "Grey beanie": "HATS/GREY-BEANIE"},
    "jewelry": {"Silver nose ring": "JEWELRY/SMALL-SILVER-NOSERING"},
    "background": {name: "BACKGROUND/" + name.upper().replace(" ", "-") for name in (
        "Tangerine", "Cobalt blue", "Hot pink", "Seafoam teal", "Butter yellow", "Plum", "White", "Black"
    )},
}
defaults = {
    "fur": "Grey", "horns": "White", "clothing": "Grey turtleneck",
    "eyewear": "Black glasses", "headwear": None, "jewelry": None, "background": "Tangerine",
}


def slug(value):
    return value.lower().replace(" ", "-").replace("/", "-")


@lru_cache(maxsize=42)
def original(name):
    im = Image.open(source / (name + ".png")).convert("RGBA")
    if im.size != (1024, 1024):
        raise ValueError("Unexpected original size for " + name)
    return im


def files(group, name):
    return options[group][name].split("|") if name else []


def compose(look, thumbnail=False):
    if thumbnail:
        canvas = Image.new("RGBA", (1024, 1024), "#635e58")
    else:
        canvas = original(files("background", look["background"])[0]).copy()
    for group in ("fur", "horns", "clothing", "eyes", "eyewear", "headwear", "jewelry"):
        layers = ["EYES/BASIC"] if group == "eyes" else files(group, look.get(group))
        for layer in layers:
            canvas.alpha_composite(original(layer))
    return canvas


for folder in ("layers", "choices"):
    (art / folder).mkdir(parents=True, exist_ok=True)
names = {"EYES/BASIC"}
catalog = {}
for group, choices in options.items():
    catalog[group] = []
    for name in choices:
        layers = files(group, name)
        names.update(layers)
        choice = {"id": slug(name), "name": name, "layers": [slug(layer) for layer in layers]}
        if group == "background":
            bg = original(layers[0])
            if bg.getbbox() != (0, 0, 1024, 1024):
                raise ValueError("Background must cover the canvas")
            choice["color"] = "#%02x%02x%02x" % bg.getpixel((512, 512))[:3]
        else:
            sample = {"fur": "Grey", "horns": "White", group: name}
            thumb = compose(sample, thumbnail=True)
            bounds = {"eyewear": (210, 185, 795, 770), "jewelry": (280, 285, 700, 705),
                      "headwear": (90, 0, 930, 840), "horns": (50, 0, 930, 880)}
            if group in bounds:
                thumb = thumb.crop(bounds[group])
            thumb.thumbnail((256, 256), Image.Resampling.LANCZOS)
            thumb.convert("RGB").save(art / "choices" / (group + "-" + slug(name) + ".webp"), quality=88)
        catalog[group].append(choice)

for name in sorted(names):
    original(name).save(art / "layers" / (slug(name) + ".webp"), lossless=True, method=4)
starter = compose(defaults).convert("RGB")
starter.thumbnail((800, 800), Image.Resampling.LANCZOS)
starter.save(art / "starter.webp", quality=92)
data = {"choices": catalog, "defaults": {g: slug(v) if v else None for g, v in defaults.items()}}
(site / "herd-studio-palette.js").write_text(
    "// Generated by scripts/prepare-herd-studio.py from the curated original layers.\n"
    + "window.HerdStudioPalette = " + json.dumps(data, indent=2) + ";\n"
)
